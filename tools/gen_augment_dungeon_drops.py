"""Generate the Augmentation Dungeon catalyst drop table.

Reads (relative to repo root):
    modules/custom/lua/augment_catalog.lua      catalyst -> { cat, tier, label }
    modules/custom/lua/augment_item_names.lua   catalyst -> item display token

Writes:
    modules/custom/lua/augment_dungeon_drops_data.lua   (AUTO-GENERATED)

Strategy (owner-approved 2026-07-03): each of the seven "Augmentation
Dungeons" (dungeon_catalog.lua categories) owns a FAMILY of augment-catalog
categories (`cat` 1..24), so players pick a dungeon by the kind of augment
they want:

  * trash slots 1-12 : the family's twelve lowest-tier catalysts (tier asc,
                       cat asc, itemId asc) -- one FIXED catalyst per trash
                       mob, extending the 1:1 "this mob drops this item"
                       philosophy of augment_catalyst_mobs.lua.
  * boss pool        : every remaining family catalyst with tier >= 3
                       (Magus/Sage rank gear). Falls back to the highest
                       remaining tier if a family has no T3+.

Every catalog `cat` MUST be claimed by exactly one dungeon -- the script
fails loudly on unmapped or double-mapped categories so new catalog
categories can't silently vanish from the drop economy.

Re-run whenever augment_catalog.lua changes, then commit the data file:
    python tools/gen_augment_dungeon_drops.py
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]

CATALOG_PATH = REPO_ROOT / "modules/custom/lua/augment_catalog.lua"
NAMES_PATH   = REPO_ROOT / "modules/custom/lua/augment_item_names.lua"
OUT_PATH     = REPO_ROOT / "modules/custom/lua/augment_dungeon_drops_data.lua"

TRASH_SLOTS = 12

# dungeonKey (dungeon_catalog.lua) -> (family label, augment_catalog `cat` list)
FAMILIES: list[tuple[str, str, list[int]]] = [
    ("ordellesCaves",  "Melee Offense",             [1, 2, 3]),
    ("gusgenMines",    "Survival & Defense",        [5, 6, 8, 16, 22]),
    ("kuftalTunnel",   "Weapon Mastery & Speed",    [9, 23, 24]),
    ("gustavTunnel",   "Ranged & Pet",              [4, 20]),
    ("ifritsCauldron", "Nuking & Magic Offense",    [10, 11]),
    ("feiYin",         "Healing & MP Support",      [12, 13, 17, 18, 19]),
    ("ranguemontPass", "Songs, Utility & Affinity", [7, 14, 15, 21]),
]

ENTRY_RE = re.compile(
    r"^\s*\[(\d+)\]\s*=\s*\{.*?cat\s*=\s*(\d+),\s*tier\s*=\s*(\d+),\s*label\s*=\s*'([^']*)'",
    re.M,
)
NAME_RE = re.compile(r"^\s*\[(\d+)\]\s*=\s*'([^']*)'", re.M)


def lua_quote(s: str) -> str:
    return s.replace("\\", "\\\\").replace("'", "\\'")


def main() -> int:
    catalog_text = CATALOG_PATH.read_text(encoding="utf-8")
    names_text   = NAMES_PATH.read_text(encoding="utf-8")

    names = {int(i): n for i, n in NAME_RE.findall(names_text)}

    entries = []
    for item_id, cat, tier, label in ENTRY_RE.findall(catalog_text):
        entries.append({
            "id":    int(item_id),
            "cat":   int(cat),
            "tier":  int(tier),
            "label": label,
            "item":  names.get(int(item_id)),
        })

    # Fail-closed: the regex must account for every catalog entry.
    raw_count = len(re.findall(r"^\s*\[\d+\]\s*=\s*\{", catalog_text, re.M))
    if raw_count != len(entries):
        print(f"FATAL: parsed {len(entries)} entries but catalog has {raw_count} "
              f"'[id] = {{' lines -- entry format drifted, fix ENTRY_RE.")
        return 1

    # Fail-closed: every cat claimed exactly once.
    claimed: dict[int, str] = {}
    for key, _fam, cats in FAMILIES:
        for c in cats:
            if c in claimed:
                print(f"FATAL: cat {c} mapped to both {claimed[c]} and {key}")
                return 1
            claimed[c] = key
    unmapped = sorted({e["cat"] for e in entries} - set(claimed))
    if unmapped:
        print(f"FATAL: catalog cats {unmapped} not mapped to any dungeon -- "
              f"add them to FAMILIES in {Path(__file__).name}.")
        return 1

    out = []
    out.append("-----------------------------------")
    out.append("-- augment_dungeon_drops_data.lua")
    out.append("-- AUTO-GENERATED by tools/gen_augment_dungeon_drops.py -- DO NOT HAND-EDIT.")
    out.append("-- Re-run the script after augment_catalog.lua changes and commit both.")
    out.append("--")
    out.append("-- Per Augmentation Dungeon (dungeon_catalog.lua keys):")
    out.append("--   family : player-facing name of the stat family this dungeon owns")
    out.append("--   trash  : [slot 1-12] = fixed catalyst for that trash mob (roster order)")
    out.append("--   boss   : pool the boss draws from (family tier-3/4 remainder)")
    out.append("-- Consumed by augment_dungeon_drops.lua (runtime) and")
    out.append("-- tools/docgen/generators/augment_dungeon_drops.py (docs).")
    out.append("-----------------------------------")
    out.append("return {")

    summary = []
    for key, family, cats in FAMILIES:
        fam_entries = sorted(
            (e for e in entries if e["cat"] in cats),
            key=lambda e: (e["tier"], e["cat"], e["id"]),
        )
        if len(fam_entries) < TRASH_SLOTS:
            print(f"FATAL: family {key} has only {len(fam_entries)} catalysts "
                  f"(needs >= {TRASH_SLOTS} for trash slots).")
            return 1

        trash = fam_entries[:TRASH_SLOTS]
        trash_ids = {e["id"] for e in trash}
        boss = [e for e in fam_entries if e["id"] not in trash_ids and e["tier"] >= 3]
        if not boss:
            # Fallback: highest remaining tier so every boss pays something.
            rest = [e for e in fam_entries if e["id"] not in trash_ids]
            top = max(e["tier"] for e in rest)
            boss = [e for e in rest if e["tier"] == top]

        def fmt(e: dict) -> str:
            item = f", item = '{lua_quote(e['item'])}'" if e["item"] else ""
            return (f"{{ id = {e['id']}, tier = {e['tier']}, cat = {e['cat']}, "
                    f"label = '{lua_quote(e['label'])}'{item} }}")

        out.append(f"    {key} =")
        out.append("    {")
        out.append(f"        family = '{lua_quote(family)}',")
        out.append("        trash =")
        out.append("        {")
        for slot, e in enumerate(trash, 1):
            out.append(f"            [{slot}] = {fmt(e)},")
        out.append("        },")
        out.append("        boss =")
        out.append("        {")
        for e in boss:
            out.append(f"            {fmt(e)},")
        out.append("        },")
        out.append("    },")

        tiers = {}
        for e in fam_entries:
            tiers[e["tier"]] = tiers.get(e["tier"], 0) + 1
        summary.append((key, family, len(fam_entries), len(boss), tiers))

    out.append("}")
    OUT_PATH.write_text("\n".join(out) + "\n", encoding="utf-8")

    print(f"wrote {OUT_PATH.relative_to(REPO_ROOT)}  ({len(entries)} catalog entries)")
    for key, family, n, nboss, tiers in summary:
        tier_str = " ".join(f"T{t}:{c}" for t, c in sorted(tiers.items()))
        print(f"  {key:<15} {family:<27} n={n:<3} trash={TRASH_SLOTS} boss={nboss:<3} [{tier_str}]")
    covered = TRASH_SLOTS * len(FAMILIES) + sum(s[3] for s in summary)
    print(f"  dungeon-obtainable catalysts: {covered}/{len(entries)} "
          f"(rest stay open-world-only via augment_catalyst_mobs.lua)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
